"""Construct the registered K1 demands using the frozen K0 physical generator.

The K0 source and its generated bytes remain untouched. This script changes
only the stage and seed range; all online and evaluation fields are inherited.
"""
import argparse
import json
from pathlib import Path

import ws31_demand_construct as frozen

K1_SEEDS = tuple(range(5310101, 5310125))
FROZEN_CONSTRUCTOR_SHA = '261cee65f90dd72119694f00d93778e705ec59fa84b302984cc64000b1ebdc8d'


def bundle_bytes(family, seed):
    if family not in ('D1', 'D2') or seed not in K1_SEEDS:
        raise ValueError('Unregistered K1 family or seed')
    if frozen.sha_bytes(Path(frozen.__file__).read_bytes()) != FROZEN_CONSTRUCTOR_SHA:
        raise ValueError('Frozen physical constructor changed')
    online, evaluation, metadata = frozen.construct(family, seed)
    metadata['stage'] = 'K1'
    files = {
        'online-current.csv': frozen.csv_bytes(online, frozen.ONLINE_FIELDS),
        'evaluation-only.csv': frozen.csv_bytes(evaluation, frozen.EVAL_FIELDS),
    }
    manifest = dict(
        metadata, schema='ws31-abstract-demand-r1',
        protocol_sha256=frozen.PROTOCOL_SHA,
        constructor_sha256=FROZEN_CONSTRUCTOR_SHA,
        k1_generator_sha256=frozen.sha_bytes(Path(__file__).read_bytes()),
        status='ABSTRACT_ONLY_NOT_NATIVE_RUNTIME_MANIFEST',
        native_adapter_verified=False, endpoint_correctness_verified=False,
        files={name: {'sha256': frozen.sha_bytes(raw), 'bytes': len(raw)}
               for name, raw in files.items()},
    )
    files['manifest.json'] = (json.dumps(manifest, sort_keys=True, indent=2) + '\n').encode('utf-8')
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write-k1', action='store_true', required=True)
    parser.parse_args()
    implementation = Path(__file__).resolve().parents[1]
    main_root = implementation.parents[1] / 'workspace/LarryBUPT-conweave-ns3/docs/research/ws31/main'
    release_path = main_root / 'evidence/c1-k1-input-freeze-r1/constructor-release.json'
    release = json.loads(release_path.read_text(encoding='utf-8'))
    if (release.get('generator_sha256') != frozen.sha_bytes(Path(__file__).read_bytes()) or
            release.get('protocol_sha256') != frozen.PROTOCOL_SHA or
            release.get('seed_first') != K1_SEEDS[0] or
            release.get('seed_last') != K1_SEEDS[-1]):
        raise SystemExit('K1 exact-source input release missing')
    root = implementation / 'results/ws31-consensus-v2-inputs-r1/K1'
    destinations = [(family, seed, root / '{}-{}'.format(family, seed))
                    for family in ('D1', 'D2') for seed in K1_SEEDS]
    if any(path.exists() for _, _, path in destinations):
        raise SystemExit('K1 output already exists; preserve prior attempt')
    for family, seed, path in destinations:
        content = bundle_bytes(family, seed)
        path.mkdir(parents=True, exist_ok=False)
        for name, raw in content.items():
            with (path / name).open('xb') as handle:
                handle.write(raw)
    print(json.dumps({'status': 'ABSTRACT_K1_CONSTRUCTION_COMPLETE',
                      'demands': len(destinations), 'root': str(root),
                      'simulator_runs': 0}))


if __name__ == '__main__':
    main()
